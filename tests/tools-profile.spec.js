test('Respaldo personal: descarga, vista previa, cancelación, rechazo, rollback e importación desde demo', async ({ page }) => {
  await personal(page);
  const fixture = backupFixture();
  await writeRecords(page, 'personal', fixture.stores);
  await page.reload();
  await expect(page.getByRole('textbox', { name: 'Alias', exact: true })).toHaveValue('Deportista de prueba');
  const original = await readDatabase(page, 'personal');
  await selectMode(page, 'demo');
  const demoBefore = await readDatabase(page, 'demo');
  const appBefore = await readDatabase(page, 'app');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exportar respaldo personal', exact: true }).click();
  const download = await downloadPromise;
  const exported = JSON.parse(await readFile(await download.path(), 'utf8'));
  expect(exported.stores).toEqual(original);
  expect(exported.schemaVersion).toBe(1); expect(exported.scope).toBe('personal');
  await importFile(page, exported);
  await expect(preview(page)).toContainText('Vista previa validada');
  await expect(preview(page).getByRole('button', { name: 'Cancelar', exact: true })).toBeFocused();
  await page.setViewportSize({ width: 320, height: 844 });
  expect(await preview(page).evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth)).toBe(true);
  await page.screenshot({ path: '.cache/ft008-backup-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1536, height: 1024 });
  await preview(page).getByRole('button', { name: 'Cancelar', exact: true }).click();
  expect(await readDatabase(page, 'personal')).toEqual(original);
  for (const content of ['{', { ...exported, schemaVersion: 999 }, { ...exported, stores: { ...exported.stores, setRecords: [] } }]) {
    await importFile(page, content);
    await expect(page.locator('#backup-error')).toContainText('No se importó ningún dato');
    await expect(preview(page)).not.toBeVisible();
    expect(await readDatabase(page, 'personal')).toEqual(original);
  }
  const changed = structuredClone(exported); changed.stores.profiles[0].alias = 'Restaurado';
  await page.evaluate(() => {
    const add = IDBObjectStore.prototype.add;
    IDBObjectStore.prototype.add = function (...args) { if (window.failRestore && this.name === 'workouts') throw new DOMException('Fallo simulado', 'QuotaExceededError'); return add.apply(this, args); };
    window.failRestore = true;
  });
  await importFile(page, changed);
  await preview(page).getByRole('button', { name: 'Reemplazar datos personales', exact: true }).click();
  await expect(preview(page).getByRole('alert')).toContainText('espacio');
  expect(await readDatabase(page, 'personal')).toEqual(original);
  await page.evaluate(() => { window.failRestore = false; });
  await preview(page).getByRole('button', { name: 'Reemplazar datos personales', exact: true }).click();
  await expect(preview(page)).not.toBeVisible();
  await expect(page.locator('.profile-feedback')).toContainText('Respaldo restaurado');
  const restored = await readDatabase(page, 'personal');
  expect(restored).toEqual(changed.stores);
  expect(await readDatabase(page, 'demo')).toEqual(demoBefore);
  expect(await readDatabase(page, 'app')).toEqual(appBefore);
  // A concurrent edit after preview must abort replacement before any clear.
  await importFile(page, exported);
  await expect(preview(page)).toBeVisible();
  await writeRecords(page, 'personal', { profiles: [{ ...restored.profiles[0], alias: 'Cambio en otra pestaña' }] });
  const concurrent = await readDatabase(page, 'personal');
  await preview(page).getByRole('button', { name: 'Reemplazar datos personales', exact: true }).click();
  await expect(preview(page).getByRole('alert')).toContainText('cambiaron desde la vista previa');
  expect(await readDatabase(page, 'personal')).toEqual(concurrent);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Restablecer datos personales', exact: true }).click();
  const reset = page.getByRole('dialog', { name: '¿Restablecer datos personales?', exact: true });
  await reset.getByRole('button', { name: 'Cancelar', exact: true }).click();
  expect(await readDatabase(page, 'personal')).toEqual(concurrent);
  await page.getByRole('button', { name: 'Restablecer datos personales', exact: true }).click();
  await reset.getByRole('button', { name: 'Eliminar datos personales', exact: true }).click();
  await expect(reset).not.toBeVisible();
  expect(Object.values(await readDatabase(page, 'personal')).every(rows => rows.length === 0)).toBe(true);
  expect(await readDatabase(page, 'demo')).toEqual(demoBefore);
  // Restore the actual downloaded backup and recover its active draft.
  await importFile(page, exported);
  await preview(page).getByRole('button', { name: 'Reemplazar datos personales', exact: true }).click();
  await expect(preview(page)).not.toBeVisible();
  expect(await readDatabase(page, 'personal')).toEqual(original);
  await selectMode(page, 'personal');
  await expect(page.getByRole('textbox', { name: 'Alias', exact: true })).toHaveValue('Deportista de prueba');
  await route(page, 'rutina-activa');
  await page.getByRole('button', { name: 'Continuar entrenamiento', exact: true }).click();
  await expect(page.locator('.workout-session h2')).toHaveText('Rutina de prueba');
  await expect(page.locator('.set-reference').first()).toContainText('110,2 lb × 8');
});
