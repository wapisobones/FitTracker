import { mkdir } from 'node:fs/promises';
import { test, expect } from '@playwright/test';
import { readDatabase, writeRecords, selectMode, requestReset } from './helpers/storage.js';

const modal = (page, name) => page.getByRole('dialog', { name, exact: true });
const form = (page) => page.locator('#generator-form');
const group = (page, name) => page.locator(`[data-generator-muscle="${name}"]`);
async function start(page, route = 'generador') {
  await page.goto(`./#/${route}`);
  await page.getByRole('button', { name: 'Comenzar mi entrenamiento', exact: true }).click();
  if (route === 'generador') await expect(page.getByRole('button', { name: 'Generar propuesta', exact: true })).toBeEnabled();
}
async function generate(page) {
  await page.getByRole('button', { name: 'Generar propuesta', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Guardar en Mis rutinas', exact: true })).toBeVisible();
}

test('Mapa/lista, sesión editable sin escrituras, guardado atómico e integración con entrenamiento', async ({ page }) => {
  await start(page);
  const map = page.getByRole('button', { name: 'Pecho, vista frontal', exact: true });
  await map.focus(); await page.keyboard.press('Enter');
  await expect(group(page, 'Pecho')).toHaveAttribute('aria-pressed', 'true');
  await page.keyboard.press('Space');
  await expect(group(page, 'Pecho')).toHaveAttribute('aria-pressed', 'false');
  await group(page, 'Pecho').click();
  await group(page, 'Core').click();
  await expect(map).toHaveAttribute('aria-pressed', 'true');
  const before = await readDatabase(page, 'personal');
  await generate(page);
  await expect(page.locator('.session-tabs strong')).toHaveCount(1);
  expect((await readDatabase(page, 'personal')).routines).toEqual(before.routines);
  await page.getByRole('button', { name: 'Editar rutina', exact: true }).click();
  await modal(page, 'Editar rutina').getByRole('textbox', { name: 'Nombre de rutina', exact: true }).fill('Mi sesión editable');
  await modal(page, 'Editar rutina').getByRole('button', { name: 'Guardar rutina', exact: true }).click();
  await page.getByRole('button', { name: 'Editar sesión', exact: true }).click();
  await modal(page, 'Editar sesión').getByRole('textbox', { name: 'Nombre de sesión', exact: true }).fill('Sesión propia');
  await modal(page, 'Editar sesión').getByRole('button', { name: 'Guardar sesión', exact: true }).click();
  await page.getByRole('button', { name: 'Editar objetivos de Flexiones', exact: true }).click();
  const goals = modal(page, 'Configurar ejercicio');
  await goals.getByRole('spinbutton', { name: 'Series', exact: true }).fill('3');
  await goals.getByRole('spinbutton', { name: 'Repeticiones mínimas', exact: true }).fill('6');
  await goals.getByRole('spinbutton', { name: 'Repeticiones máximas', exact: true }).fill('8');
  await goals.getByRole('spinbutton', { name: 'Descanso (segundos)', exact: true }).fill('45');
  await goals.getByRole('button', { name: 'Guardar objetivos', exact: true }).click();
  await expect(page.locator('.prescription-targets').first().locator('dd')).toHaveText(['3', '6–8', '45 s']);
  await page.getByRole('button', { name: 'Subir Dead bug', exact: true }).click();
  await expect(page.locator('.prescription-name strong').first()).toHaveText('Dead bug');
  expect((await readDatabase(page, 'personal')).routines).toEqual(before.routines);
  await mkdir('.cache', { recursive: true });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: '.cache/ft007-generator-desktop.png', fullPage: true });
  await page.evaluate(() => {
    const put = IDBObjectStore.prototype.put;
    window.failGeneratedSave = true;
    IDBObjectStore.prototype.put = function () {
      if (window.failGeneratedSave && this.name === 'routines') throw new DOMException('Prueba', 'QuotaExceededError');
      return put.apply(this, arguments);
    };
    const add = IDBObjectStore.prototype.add;
    IDBObjectStore.prototype.add = function () {
      if (window.failGeneratedSave && this.name === 'routines') throw new DOMException('Prueba', 'QuotaExceededError');
      return add.apply(this, arguments);
    };
  });
  await page.getByRole('button', { name: 'Guardar en Mis rutinas', exact: true }).click();
  await expect(page.locator('.generator-error')).toContainText('No hay espacio suficiente');
  const failed = await readDatabase(page, 'personal');
  expect(failed.routines).toEqual(before.routines); expect(failed.routineSessions).toEqual(before.routineSessions);
  await expect(page.locator('.routine-detail h2')).toHaveText('Mi sesión editable');
  await page.evaluate(() => { window.failGeneratedSave = false; });
  await page.getByRole('button', { name: 'Guardar en Mis rutinas', exact: true }).evaluate((button) => { button.click(); button.click(); });
  await expect(page.getByRole('link', { name: 'Ver en Mis rutinas', exact: true })).toBeVisible();
  const saved = await readDatabase(page, 'personal');
  expect(saved.routines).toHaveLength(1); expect(saved.routines[0].origin).toBe('generator');
  expect(saved.routineSessions).toHaveLength(1);
  await page.getByRole('link', { name: 'Ver en Mis rutinas', exact: true }).click();
  await page.reload();
  await expect(page.locator('.routine-detail h2')).toHaveText('Mi sesión editable');
  await expect(page.locator('.session-heading h3')).toHaveText('Sesión propia');
  await expect(page.locator('.routine-meta')).toContainText('Generador');
  await page.getByRole('link', { name: 'Iniciar sesión', exact: true }).click();
  await page.getByRole('button', { name: 'Iniciar entrenamiento', exact: true }).click();
  await expect(page.locator('.workout-session h2')).toHaveText('Mi sesión editable');
  expect((await readDatabase(page, 'personal')).workouts[0].entries[0].exercise.name).toBe('Dead bug');
});

test('Programa de cuatro sesiones, confirmación de reemplazo, memoria por ámbito y rutinas independientes', async ({ page }) => {
  await start(page);
  const now = new Date().toISOString();
  const existing = { id: 'e7000000-0000-4000-8000-000000001111', name: 'Rutina anterior intacta', description: '', origin: 'manual', revision: 1, sessionIds: [], nextSessionId: null, cyclePolicy: 'sequential-wrap', createdAt: now, updatedAt: now };
  await writeRecords(page, 'personal', { routines: [existing] });
  for (const name of ['Pecho', 'Espalda', 'Piernas', 'Hombros', 'Brazos', 'Core']) await group(page, name).click();
  await form(page).getByRole('combobox', { name: 'Modalidad', exact: true }).selectOption('program');
  await form(page).getByRole('combobox', { name: 'Nivel', exact: true }).selectOption('Intermedio');
  await form(page).getByRole('combobox', { name: 'Sesiones por semana', exact: true }).selectOption('4');
  await form(page).getByRole('spinbutton', { name: 'Duración aproximada (min)', exact: true }).fill('60');
  await generate(page);
  await expect(page.locator('.session-tabs strong')).toHaveCount(4);
  await page.getByRole('button', { name: 'Editar rutina', exact: true }).click();
  await modal(page, 'Editar rutina').getByRole('textbox', { name: 'Nombre de rutina', exact: true }).fill('Mi programa de cuatro');
  await modal(page, 'Editar rutina').getByRole('button', { name: 'Guardar rutina', exact: true }).click();
  await page.getByRole('button', { name: 'Generar propuesta', exact: true }).click();
  await expect(modal(page, '¿Reemplazar la propuesta?').getByRole('button', { name: 'Cancelar', exact: true })).toBeFocused();
  await modal(page, '¿Reemplazar la propuesta?').getByRole('button', { name: 'Cancelar', exact: true }).click();
  await expect(page.locator('.routine-detail h2')).toHaveText('Mi programa de cuatro');
  const personalBefore = await readDatabase(page, 'personal');
  expect(personalBefore.routines).toEqual([existing]);
  await selectMode(page, 'demo');
  await expect(group(page, 'Pecho')).toHaveAttribute('aria-pressed', 'false');
  await group(page, 'Pecho').click();
  await generate(page);
  await page.getByRole('button', { name: 'Guardar en Mis rutinas', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Ver en Mis rutinas', exact: true })).toBeVisible();
  expect((await readDatabase(page, 'demo')).routines).toHaveLength(1);
  expect(await readDatabase(page, 'personal')).toEqual(personalBefore);
  const reset = await requestReset(page);
  await reset.getByRole('button', { name: 'Restablecer demostración', exact: true }).click();
  await expect(page.locator('.operation-status')).toContainText('restablecida');
  await expect(page.getByRole('link', { name: 'Ver en Mis rutinas', exact: true })).toHaveCount(0);
  await expect(group(page, 'Pecho')).toHaveAttribute('aria-pressed', 'false');
  expect((await readDatabase(page, 'demo')).routines).toHaveLength(0);
  expect(await readDatabase(page, 'personal')).toEqual(personalBefore);
  await selectMode(page, 'personal');
  await expect(page.locator('.routine-detail h2')).toHaveText('Mi programa de cuatro');
  await expect(page.locator('.session-tabs strong')).toHaveCount(4);
  await page.getByRole('button', { name: 'Guardar en Mis rutinas', exact: true }).click();
  await page.getByRole('link', { name: 'Ver en Mis rutinas', exact: true }).click();
  await page.reload();
  await expect(page.locator('.routine-detail h2')).toHaveText('Mi programa de cuatro');
  await expect(page.locator('.session-tabs strong')).toHaveCount(4);
  const result = await readDatabase(page, 'personal');
  expect(result.routines.find((routine) => routine.id === existing.id)).toEqual(existing);
  expect(result.routineSessions).toHaveLength(4);
});

